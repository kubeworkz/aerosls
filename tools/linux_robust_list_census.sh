#!/usr/bin/env bash
# linux_robust_list_census.sh — the census trace that lets set_robust_list
# (273) into the classification table.
#
# §5.6's rule is that a table row is BUILT from a trace, never from belief:
# the number must appear in a real program's syscall stream, with the
# provenance that lets a reader re-run the measurement. The candidate artifact
# (tools/linux_syscall_census.txt) traces the aerobackup candidate, which never
# registers a robust list (static musl, no pthreads). So this measures the one
# flow the row exists for: a program that registers a robust_list_head.
#
# Method: a small C program (memset a 24-byte head, call set_robust_list),
# compiled on the host and traced with strace -f, entry-counted — the same
# method and the same columns as the candidate artifact
# (tools/linux_syscall_census.sh) and as tools/linux_rt_sigreturn_census.sh:
#
#   <syscall-number> <name> <count>
#
# The trace is also the evidence for two properties the row depends on:
#   - 273 appears once per registration, and a glibc program makes TWO calls:
#     libc's own start-up head and this program's. That is the measured reason
#     the row cannot wait for a program to ask — every glibc binary asks before
#     main (the same claim §6.1 makes about `rseq` and the loader);
#   - the call SUCCEEDS with the 24-byte head this shim accepts, which is why
#     kernel/linux_thread.h pins LINUX_ROBUST_LIST_HEAD_BYTES at sizeof(struct
#     robust_list_head) and the kernel's own row can be walked at exit.
#
# Writes tools/linux_robust_list_census.txt. Run from the repo root.
set -eu
cd "$(dirname "$0")/.." || exit 1

OUT=tools/linux_robust_list_census.txt
PROG="$(mktemp -d)/robust.c"
BIN="${PROG%.c}"
TRACE="$(mktemp)"

cat > "$PROG" <<'EOF'
/* The smallest program that registers a robust list: the only producer of 273
 * that matters to a pthread — glibc's pthread_create does exactly this call
 * with sizeof(struct robust_list_head) bytes before its first clone. */
#include <string.h>
#include <unistd.h>
#include <sys/syscall.h>
struct robust_list_head {
    void *list;
    long  futex_offset;
    void *list_op_pending;
};
int main(void) {
    struct robust_list_head head;
    memset(&head, 0, sizeof(head));
    if (syscall(SYS_set_robust_list, &head, sizeof(head)) != 0) return 1;
    return 0;
}
EOF

CC="${CC:-cc}"
command -v "$CC" >/dev/null 2>&1 || { echo "ABORT: no C compiler ($CC)" >&2; exit 2; }
command -v strace >/dev/null 2>&1 || { echo "ABORT: strace not installed" >&2; exit 2; }

"$CC" -O0 -o "$BIN" "$PROG"
sha="$(sha256sum "$BIN" | awk '{print $1}')"

# One full trace, entry-counted, exactly the candidate artifact's method.
strace -f -o "$TRACE" "$BIN"

count="$(grep -cE '^[0-9]+ +set_robust_list\(' "$TRACE" || true)"
[ -n "$count" ] && [ "$count" -gt 0 ] || {
    echo "ABORT: the trace contains no set_robust_list call" >&2
    sed -n '1,20p' "$TRACE" >&2
    exit 1
}

{
    echo "# AeroSLS E7 Linux syscall census -- generated by tools/linux_robust_list_census.sh"
    echo "# candidate: robust (registers a robust_list_head: the only producer of 273)"
    echo "# provenance: one set_robust_list(&head, sizeof head) — see this script"
    echo "# binary: a host-built single-function program, rebuilt by the script"
    echo "# target: $(uname -m)-linux-gnu"
    echo "# sha256: $sha"
    echo "# host: $(uname -srm)"
    echo "# date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# method: strace -f full trace, entry-counted"
    echo "# columns: <syscall-number> <name> <count>"
    echo "# note: 273 appears once per registration; glibc registers its own head"
    echo "#       at start-up, so a glibc program's trace carries two (libc's and"
    echo "#       the program's) — every glibc binary asks before main. The"
    echo "#       24-byte head this shim accepts is the layout the kernel walks"
    echo "#       at the thread's exit (TG-1 I5)."
    echo "273 set_robust_list $count"
} > "$OUT"

echo "wrote $OUT ($count set_robust_list call(s))"
