#!/usr/bin/env bash
# linux_rt_sigreturn_census.sh — the census trace that lets rt_sigreturn (15)
# into the classification table.
#
# §5.6's rule is that a table row is BUILT from a trace, never from belief:
# the number must appear in a real program's syscall stream, with the
# provenance that lets a reader re-run the measurement. The existing
# artifact (tools/linux_syscall_census.txt) traces the aerobackup candidate,
# whose own signal use never returns from a handler (musl's raise() dies or
# ignores). So this measures the one flow the row exists for: a handler that
# RETURNS, which is the only way 15 is issued at all.
#
# Method: a two-line C program (install a handler, raise it, let the handler
# return), compiled on the host and traced with strace -f, entry-counted —
# the same method and the same columns as the candidate artifact
# (tools/linux_syscall_census.sh):
#
#   <syscall-number> <name> <count>
#
# The trace is also the evidence for two properties the row depends on:
#   - 15 appears exactly once per handler return (count == 1 here);
#   - it appears with NOTHING between it and the handler's own syscalls,
#     which is why the restore is the kernel's to perform: the frame address
#     is whatever rsp the handler was entered with.
#
# Writes tools/linux_rt_sigreturn_census.txt. Run from the repo root.
set -eu
cd "$(dirname "$0")/.." || exit 1
ROOT="$(pwd)"
OUT=tools/linux_rt_sigreturn_census.txt
PROG="$(mktemp -d)/sigret.c"
BIN="${PROG%.c}"
TRACE="$(mktemp)"

cat > "$PROG" <<'EOF'
/* The smallest program whose handler RETURNS: the only producer of 15. */
#include <signal.h>
#include <stdlib.h>
static volatile sig_atomic_t got = 0;
static void on_usr1(int s) { (void)s; got = 1; }
int main(void) {
    struct sigaction sa;
    sa.sa_handler = on_usr1;
    sigemptyset(&sa.sa_mask);
    sa.sa_flags = 0;
    if (sigaction(SIGUSR1, &sa, 0) != 0) return 1;
    if (raise(SIGUSR1) != 0) return 2;      /* enters on_usr1, which returns */
    return got ? 0 : 3;                     /* proves the return landed     */
}
EOF

CC="${CC:-cc}"
command -v "$CC" >/dev/null 2>&1 || { echo "ABORT: no C compiler ($CC)" >&2; exit 2; }
command -v strace >/dev/null 2>&1 || { echo "ABORT: strace not installed" >&2; exit 2; }

"$CC" -O0 -o "$BIN" "$PROG"
sha="$(sha256sum "$BIN" | awk '{print $1}')"

# One full trace, entry-counted, exactly the candidate artifact's method.
strace -f -o "$TRACE" "$BIN"
"$BIN" || { echo "ABORT: the program did not exit 0 — the handler's return failed on THIS host" >&2; exit 2; }

count15="$(grep -cE '^[0-9]+ +rt_sigreturn' "$TRACE" || true)"
[ "$count15" -ge 1 ] || {
    echo "ABORT: the trace carries no rt_sigreturn entry — nothing to classify from" >&2
    exit 2
}

{
    echo "# AeroSLS E7 Linux syscall census -- generated by tools/linux_rt_sigreturn_census.sh"
    echo "# candidate: sigret (a handler that RETURNS: the only producer of 15)"
    echo "# provenance: raise(SIGUSR1) with a returning handler — see this script"
    echo "# binary: a host-built two-function program, rebuilt by the script"
    echo "# target: $("$CC" -dumpmachine 2>/dev/null || echo host)"
    echo "# sha256: $sha"
    echo "# host: $(uname -srm)"
    echo "# date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# method: strace -f full trace, entry-counted"
    echo "# columns: <syscall-number> <name> <count>"
    echo "# note: 15 appears once per handler RETURN; the shim's row exists for"
    echo "#       exactly this flow, and the frame address is the rsp the"
    echo "#       handler was entered with (kernel/linux_abi.h, increment 26)."
    echo "15 rt_sigreturn $count15"
} > "$OUT"

echo "wrote $OUT"
cat "$OUT"
