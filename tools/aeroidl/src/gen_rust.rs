/// Map an IDL type JSON to a Rust type string.
fn json_type_to_rust(ty: &Value) -> String {
    let kind = ty["kind"].as_str().unwrap_or("i32");
    match kind {
        "i8" => "i8".into(),
        "i16" => "i16".into(),
        "i32" => "i32".into(),
        "i64" => "i64".into(),
        "u8" => "u8".into(),
        "u16" => "u16".into(),
        "u32" => "u32".into(),
        "u64" => "u64".into(),
        "f32" => "f32".into(),
        "f64" => "f64".into(),
        "bool" => "bool".into(),
        "string" => "u16 /* cap handle */".into(),
        "bytes" => "u16 /* cap handle */".into(),
        "named" => ty["name"].as_str().unwrap_or("Unknown").into(),
        "array" => {
            let inner = ty.get("inner").map(|i| json_type_to_rust(i)).unwrap_or_default();
            format!("ArenaSlice<{inner}>")
        }
        "option" => {
            let inner = ty.get("inner").map(|i| json_type_to_rust(i)).unwrap_or_default();
            format!("Option<{inner}>")
        }
        "result" => {
            let ok = ty.get("inner").map(|i| json_type_to_rust(i)).unwrap_or("()".into());
            format!("AeroidlResult<{ok}>")
        }
        "unit" => "()".into(),
        "map" => "u16 /* cap handle */".into(),
        _ => "u64 /* unknown */".into(),
    }
}

fn ownership_comment(ownership: &Value) -> String {
    match ownership.as_str().unwrap_or("inline") {
        "borrowed" => " /* @borrowed */".into(),
        "owned" => " /* @owned */".into(),
        "arena" => " /* @arena */".into(),
        _ => String::new(),
    }
}

fn to_snake_case(s: &str) -> String {
    let mut result = String::with_capacity(s.len() + 4);
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                result.push('_');
            }
            result.push(ch.to_ascii_lowercase());
        } else {
            result.push(ch);
        }
    }
    result
}

/// Calculate the payload size for a method request.
fn calculate_payload_size(params: &[Value], _return_type: &Value) -> usize {
    let mut size = 0usize;
    for p in params {
        if p["needs_cap"].as_bool().unwrap_or(false) {
            // Arena params: only the count/metadata goes in the payload
            let kind = p["ty"]["kind"].as_str().unwrap_or("array");
            if kind == "array" {
                size += 4; // count as u32
            } else {
                size += 8; // generic cap metadata
            }
        } else {
            size += p["wire_size"].as_u64().unwrap_or(0) as usize;
        }
    }
    size
}

/// Calculate the reply buffer size.
fn calculate_reply_size(return_type: &Value) -> usize {
    let kind = return_type["kind"].as_str().unwrap_or("unit");
    match kind {
        "unit" => 1, // just ok byte
        "result" => {
            // ok byte + max(ok_size, err_size) — simplified to 32 bytes
            32
        }
        "named" => 32,
        _ => 32,
    }
}

/// Look up a struct definition by name from the AST.
fn find_struct<'a>(ast: &'a Value, name: &str) -> Option<&'a Value> {
    ast["structs"].as_array()?.iter().find(|s| s["name"].as_str() == Some(name))
}

/// True if `name` refers to an enum type in the AST.
fn is_enum_type(ast: &Value, name: &str) -> bool {
    ast["enums"]
        .as_array()
        .map(|es| es.iter().any(|e| e["name"].as_str() == Some(name)))
        .unwrap_or(false)
}

/// Name of the first variant of an enum (used as a `from_raw` fallback).
fn enum_first_variant(ast: &Value, name: &str) -> Option<String> {
    ast["enums"]
        .as_array()?
        .iter()
        .find(|e| e["name"].as_str() == Some(name))?
        .get("variants")?
        .as_array()?
        .first()?
        .get("name")?
        .as_str()
        .map(|s| s.to_string())
}

/// Get struct field names from the AST.
fn get_struct_field_names(ast: &Value, type_name: &str) -> Vec<Value> {
    find_struct(ast, type_name)
        .and_then(|s| s["fields"].as_array())
        .cloned()
        .unwrap_or_default()
}

fn get_wire_size(ty: &Value) -> u64 {
    let kind = ty["kind"].as_str().unwrap_or("i32");
    match kind {
        "i8" | "u8" | "bool" => 1,
        "i16" | "u16" => 2,
        "i32" | "u32" | "f32" => 4,
        "i64" | "u64" | "f64" => 8,
        "string" | "bytes" | "array" | "map" => 8,
        _ => 8,
    }
}

