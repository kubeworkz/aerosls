fn json_type_to_c(ty: &Value, _ast: &Value) -> String {
    let kind = ty["kind"].as_str().unwrap_or("int32_t");
    match kind {
        "i8" => "int8_t".into(),
        "u8" => "uint8_t".into(),
        "i16" => "int16_t".into(),
        "u16" => "uint16_t".into(),
        "i32" => "int32_t".into(),
        "u32" => "uint32_t".into(),
        "i64" => "int64_t".into(),
        "u64" => "uint64_t".into(),
        "f32" => "float".into(),
        "f64" => "double".into(),
        "bool" => "uint8_t".into(),
        "string" | "bytes" => "uint16_t /* cap handle */".into(),
        "named" => ty["name"].as_str().unwrap_or("Unknown").into(),
        "array" => "uint16_t /* MEM cap handle */".into(),
        "option" => "uint16_t /* MEM cap handle or 0xFFFF */".into(),
        "result" => {
            let inner = ty.get("inner").map(|i| json_type_to_c(i, _ast)).unwrap_or_default();
            format!("{inner} /* via Result wrapper */")
        }
        "unit" => "void".into(),
        "map" => "uint16_t /* cap handle */".into(),
        _ => "uint64_t".into(),
    }
}

fn ownership_comment(ownership: &Value) -> String {
    match ownership.as_str().unwrap_or("inline") {
        "borrowed" => " /* @borrowed */".into(),
        "owned" => " /* @owned */".into(),
        "arena" => " /* @arena */".into(),
        _ => String::new(),
    }
}

fn enum_tag(enum_name: &str) -> String {
    // "CalcErrorKind" -> "ERROR", "LogLevel" -> "LEVEL", "PixelFormat" -> "FORMAT"
    // Extract the meaningful part: strip trailing "Kind" or "Type"
    let name = enum_name
        .strip_suffix("Kind")
        .or_else(|| enum_name.strip_suffix("Type"))
        .unwrap_or(enum_name);
    // "CalcError" -> "ERROR", "Log" -> "LOG", "Pixel" -> "PIXEL"
    let snake = to_snake_case(name);
    let parts: Vec<&str> = snake.split('_').collect();
    // Take the last meaningful word (the "type" part)
    let tag = if parts.len() > 1 {
        parts.last().unwrap_or(&"unknown")
    } else {
        parts.first().unwrap_or(&"unknown")
    };
    tag.to_uppercase()
}

/// Scan an array of parameter/type values for struct references, then
/// scan those structs' fields for enum types.
fn scan_struct_refs_for_enums(
    ast: &Value,
    params: &[Value],
    prefix: &str,
    map: &mut std::collections::HashMap<String, String>,
) {
    for p in params {
        let ty = if p.is_object() && p.get("ty").is_some() {
            &p["ty"]
        } else {
            p
        };
        let kind = ty["kind"].as_str().unwrap_or("");
        if kind == "named" {
            let name = ty["name"].as_str().unwrap_or("");
            if let Some(s) = find_struct(ast, name) {
                if let Some(fields) = s["fields"].as_array() {
                    for f in fields {
                        collect_enum_names(ast, &f["ty"], &mut |ename| {
                            map.entry(ename).or_insert_with(|| prefix.to_string());
                        });
                    }
                }
            }
        } else if kind == "result" {
            if let Some(inner) = ty.get("inner") {
                scan_struct_refs_for_enums(ast, &[inner.clone()], prefix, map);
            }
            if let Some(inner2) = ty.get("inner2") {
                scan_struct_refs_for_enums(ast, &[inner2.clone()], prefix, map);
            }
        } else if kind == "option" {
            if let Some(inner) = ty.get("inner") {
                scan_struct_refs_for_enums(ast, &[inner.clone()], prefix, map);
            }
        }
    }
}

/// Recursively collect enum type names referenced by a type expression.
fn collect_enum_names(ast: &Value, ty: &Value, f: &mut dyn FnMut(String)) {
    let kind = ty["kind"].as_str().unwrap_or("");
    match kind {
        "named" => {
            let name = ty["name"].as_str().unwrap_or("");
            // Check if this named type is an enum (not a struct)
            if let Some(enums) = ast["enums"].as_array() {
                if enums.iter().any(|e| e["name"].as_str() == Some(name)) {
                    f(name.to_string());
                }
            }
        }
        "result" => {
            if let Some(inner) = ty.get("inner") {
                collect_enum_names(ast, inner, f);
            }
            if let Some(inner2) = ty.get("inner2") {
                collect_enum_names(ast, inner2, f);
            }
        }
        "option" => {
            if let Some(inner) = ty.get("inner") {
                collect_enum_names(ast, inner, f);
            }
        }
        _ => {}
    }
}

fn to_c_name(ns: &str) -> String {
    // "aerosls.calculator" -> "calculator"
    ns.split('.').last().unwrap_or(ns).replace('-', "_")
}

fn to_c_prefix(iface_name: &str) -> String {
    // "CalculatorService" -> "CALC" (first word, uppercased)
    // "LoggingService" -> "LOG"
    // "ImageProcessingService" -> "IMAG"
    let snake = to_snake_case(iface_name);
    let first_word = snake.split('_').next().unwrap_or(&snake);
    let prefix: String = first_word.chars().take(4).map(|c| c.to_ascii_uppercase()).collect();
    prefix
}

/// Capitalized prefix for type names: "CALC" -> "Calc", "LOG" -> "Log"
fn to_c_type_prefix(prefix: &str) -> String {
    let mut chars = prefix.chars();
    match chars.next() {
        Some(first) => {
            let mut s = first.to_uppercase().to_string();
            s.extend(chars.map(|c| c.to_ascii_lowercase()));
            s
        }
        None => String::new(),
    }
}

fn to_c_name_from_prefix(prefix: &str) -> String {
    // "CALC" -> "calculator" (reverse of to_c_prefix)
    prefix.to_lowercase()
}

fn to_snake_case(s: &str) -> String {
    let mut result = String::with_capacity(s.len() + 4);
    for (i, ch) in s.chars().enumerate() {
        if ch == '_' {
            result.push('_');
        } else if ch.is_uppercase() {
            if i > 0 {
                let prev = s.as_bytes()[i - 1] as char;
                if prev != '_' && prev.is_lowercase() {
                    result.push('_');
                }
            }
            result.push(ch.to_ascii_lowercase());
        } else {
            result.push(ch);
        }
    }
    result
}

fn find_struct<'a>(ast: &'a Value, name: &str) -> Option<&'a Value> {
    ast["structs"].as_array()?.iter().find(|s| s["name"].as_str() == Some(name))
}

fn find_struct_fields<'a>(ast: &'a Value, name: &str) -> Option<Vec<&'a Value>> {
    let s = ast["structs"]
        .as_array()?
        .iter()
        .find(|s| s["name"].as_str() == Some(name))?;
    Some(s["fields"].as_array()?.iter().collect())
}

fn get_wire_size(ty: &Value) -> u64 {
    let kind = ty["kind"].as_str().unwrap_or("i32");
    match kind {
        "i8" | "u8" | "bool" => 1,
        "i16" | "u16" => 2,
        "i32" | "u32" | "f32" => 4,
        "i64" | "u64" | "f64" => 8,
        "string" | "bytes" | "array" | "map" => 8,
        _ => 8,
    }
}

/// C element type for the inner type of an array/bytes cap param.
fn c_elem_size(ty: &Value) -> &'static str {
    let kind = ty["kind"].as_str().unwrap_or("u8");
    match kind {
        "i8" | "u8" | "bool" => "uint8_t",
        "i16" | "u16" => "uint16_t",
        "i32" | "u32" => "uint32_t",
        "i64" | "u64" => "uint64_t",
        "f32" => "float",
        "f64" => "double",
        _ => "uint8_t",
    }
}

fn calculate_c_payload_size(params: &[Value]) -> usize {
    let mut size = 0usize;
    for p in params {
        if p["needs_cap"].as_bool().unwrap_or(false) {
            let kind = p["ty"]["kind"].as_str().unwrap_or("array");
            if kind == "array" || kind == "bytes" {
                size += 4; // count as u32
            }
        } else {
            size += p["wire_size"].as_u64().unwrap_or(0) as usize;
        }
    }
    size
}

